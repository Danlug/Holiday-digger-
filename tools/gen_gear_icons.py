def build(sheet_path=None):
	os.makedirs(OUT, exist_ok=True)
	names = sorted(ICONS)
	imgs = {}
	for name in names:
		rows, tier = ICONS[name]
		assert len(rows) == 16 and all(len(r) == 16 for r in rows), (name, [len(r) for r in rows])
		pal = pal_for(tier)
		img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
		px = img.load()
		for y, row in enumerate(rows):
			for x, ch in enumerate(row):
				if ch not in pal:
					raise SystemExit("буква %r в %s" % (ch, name))
				c = pal[ch]
				if c is not None:
					px[x, y] = c + (255,)
		src = img.copy().load()
		for y in range(16):
			for x in range(16):
				if src[x, y][3] != 0:
					continue
				for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
					nx, ny = x + dx, y + dy
					if 0 <= nx < 16 and 0 <= ny < 16 and src[nx, ny][3] != 0:
						px[x, y] = BASE["K"] + (255,)
						break
		big = img.resize((32, 32), Image.NEAREST)
		big.save(os.path.join(OUT, name + ".png"))
		imgs[name] = big
	print("иконок:", len(names))
	if sheet_path:
		cols = 8
		rows_n = (len(names) + cols - 1) // cols
		cell = 32 * 4 + 12
		sheet = Image.new("RGBA", (cols * cell, rows_n * cell), (0x2A, 0x20, 0x18, 255))
		for i, name in enumerate(names):
			big = imgs[name].resize((128, 128), Image.NEAREST)
			sheet.alpha_composite(big, ((i % cols) * cell + 6, (i // cols) * cell + 6))
		sheet.save(sheet_path)


if __name__ == "__main__":
	build(sys.argv[1] if len(sys.argv) > 1 else None)
