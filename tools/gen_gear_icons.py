def draw_line(grid_, x0, y0, x1, y1, ch):
	n = max(abs(x1 - x0), abs(y1 - y0))
	for i in range(n + 1):
		t = i / n if n else 0
		x = round(x0 + (x1 - x0) * t)
		y = round(y0 + (y1 - y0) * t)
		if 0 <= x < 16 and 0 <= y < 16:
			grid_[y][x] = ch


def blank():
	return [["."] * 16 for _ in range(16)]


def finish(g):
	return ["".join(r) for r in g]


def blade_rows(long=True):
	"""Меч по диагонали: остриё справа вверху, рукоять слева внизу."""
	g = blank()
	# клинок: две соседние диагонали — свет сверху, тень снизу
	draw_line(g, 4, 11, 13, 2, "L")
	draw_line(g, 5, 11, 13, 3, "B")
	draw_line(g, 5, 12, 14, 3, "D")
	# жёлоб-свечение по центру
	draw_line(g, 6, 10, 11, 5, "G")
	# гарда
	draw_line(g, 2, 9, 6, 13, "S")
	draw_line(g, 2, 10, 6, 14, "t")
	g[9][2] = "s"
	# рукоять и навершие
	draw_line(g, 3, 12, 1, 14, "n")
	g[14][1] = "N"
	g[14][0] = "S"
	return finish(g)


def amulet_rows(chain="S", pendant="B"):
	g = blank()
	draw_line(g, 3, 1, 7, 7, chain)
	draw_line(g, 12, 1, 8, 7, chain)
	for y in range(16):
		for x in range(16):
			dx, dy = x - 7.5, y - 10.5
			r = math.hypot(dx, dy)
			if r <= 4.0:
				s = dx + dy
				g[y][x] = "L" if (r > 2.6 and s < -1) else ("D" if (r > 2.6 and s > 1) else "B")
			if r <= 1.7:
				g[y][x] = "G"
	return finish(g)


