def pal_for(tier):
	l, b, d, g = TIERS[tier]
	p = dict(BASE)
	p.update({"L": l, "B": b, "D": d, "G": g})
	return p


def sym(rows):
	"""Левая половина (8 колонок) -> полная строка 16, свет/тень зеркально."""
	tr = str.maketrans("LD", "DL")
	return [r + r[::-1].translate(tr) for r in rows]


def grid(rows):
	rows = rows.strip("\n").split("\n")
	assert len(rows) == 16 and all(len(r) == 16 for r in rows), [len(r) for r in rows]
	return rows


