# Полоски HUD (здоровье, голод, бодрость) рисовались прежними заглушками art/ui/icon_*.png:
# бледная молния, расплывчатый «желудок», плоское сердце. На экране героя те же три величины —
# плотные значки с ободком (art/ui/hero/sk_*.png, tools/gen_hero_icons.py). Берём их же,
# чтобы HUD, тосты и экран героя говорили одним рисунком. Нет файла героя — остаются прежние.
HERO_ALIAS = {"hp": "sk_hp", "hunger": "sk_hunger", "stamina": "sk_stamina"}


def alias_hero_icons():
	hero = os.path.join(HERE, "..", "art", "ui", "hero")
	for name, src in HERO_ALIAS.items():
		path = os.path.join(hero, src + ".png")
		if not os.path.exists(path):
			continue
		im = Image.open(path).convert("RGBA")
		if im.size != (32, 32):
			im = im.resize((32, 32), Image.NEAREST)
		im.save(os.path.join(OUT, name + ".png"))


def build(sheet_path=None):
	os.makedirs(OUT, exist_ok=True)
	names = sorted(ICONS)
	errors = 0
	imgs = {}
	for name in names:
		rows = ICONS[name]
		if len(rows) != 16 or any(len(r) != 16 for r in rows):
			print("ОШИБКА размера:", name, len(rows), [len(r) for r in rows])
			errors += 1
			continue
		img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
		px = img.load()
		for y, row in enumerate(rows):
			for x, ch in enumerate(row):
				if ch not in PAL:
					print("ОШИБКА буквы:", name, ch)
					errors += 1
					continue
				c = PAL[ch]
				if c is not None:
					px[x, y] = c + (255,)
		# автообводка: прозрачный пиксель рядом (по четырём сторонам) с закрашенным
		src = img.copy().load()
		for y in range(16):
			for x in range(16):
				if src[x, y][3] != 0:
					continue
				for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
					nx, ny = x + dx, y + dy
					if 0 <= nx < 16 and 0 <= ny < 16 and src[nx, ny][3] != 0:
						px[x, y] = PAL["K"] + (255,)
						break
		big = img.resize((32, 32), Image.NEAREST)
		big.save(os.path.join(OUT, name + ".png"))
		imgs[name] = big
	if errors:
		sys.exit(1)
	alias_hero_icons()
	print("иконок:", len(names))
	if sheet_path:
		cols = 8
		rows_n = (len(names) + cols - 1) // cols
		cell = 32 * 5 + 16
		sheet = Image.new("RGBA", (cols * cell, rows_n * cell), (0x2A, 0x20, 0x18, 255))
		for i, name in enumerate(names):
			big = imgs[name].resize((160, 160), Image.NEAREST)
			sheet.alpha_composite(big, ((i % cols) * cell + 8, (i // cols) * cell + 8))
		sheet.save(sheet_path)


if __name__ == "__main__":
	build(sys.argv[1] if len(sys.argv) > 1 else None)
