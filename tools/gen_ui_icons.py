def gear():
	rows = []
	for y in range(16):
		row = ""
		for x in range(16):
			dx, dy = x + 0.5 - 8, y + 0.5 - 8
			r = math.hypot(dx, dy)
			a = math.degrees(math.atan2(dy, dx)) % 45
			tooth = 4.5 < r <= 7.6 and min(a, 45 - a) < 15
			body = r <= 5.6
			hole = r <= 2.5
			if hole or not (body or tooth):
				row += "."
			else:
				s = dx + dy
				row += "s" if s < -3 else ("t" if s > 3 else "S")
		rows.append(row)
	ICONS["gear"] = rows


def reset():
	"""Круговая стрелка: дуга почти полный круг и наконечник в разрыве."""
	cx, cy = 7.5, 8.0
	grid = [["."] * 16 for _ in range(16)]
	for y in range(16):
		for x in range(16):
			dx, dy = x + 0.5 - cx - 0.5, y + 0.5 - cy - 0.5
			r = math.hypot(dx, dy)
			ang = math.degrees(math.atan2(dy, dx)) % 360
			if 3.3 <= r <= 5.7 and not (322 <= ang or ang <= 28):
				grid[y][x] = "r" if dx + dy < -1 else "R"
	# наконечник: треугольник на конце дуги (угол -38°), смотрит по ходу часовой
	pts = ((14.0, 3.2), (9.4, 6.6), (14.6, 9.4))
	def inside(px, py):
		def sign(a, b, c):
			return (a[0] - c[0]) * (b[1] - c[1]) - (b[0] - c[0]) * (a[1] - c[1])
		p = (px, py)
		d1, d2, d3 = sign(p, pts[0], pts[1]), sign(p, pts[1], pts[2]), sign(p, pts[2], pts[0])
		neg = d1 < 0 or d2 < 0 or d3 < 0
		pos = d1 > 0 or d2 > 0 or d3 > 0
		return not (neg and pos)
	for y in range(16):
		for x in range(16):
			if inside(x + 0.5, y + 0.5):
				grid[y][x] = "R"
	ICONS["reset"] = ["".join(r) for r in grid]


def slash(name, color="R"):
	"""Перечёркивает иконку диагональю с тёмным кантом (для «выключено»)."""
	rows = [list(r) for r in ICONS[name]]
	for i in range(3, 13):
		x, y = i, 15 - i - 1
		for ox, oy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
			nx, ny = x + ox, y + oy
			if 0 <= nx < 16 and 0 <= ny < 16 and rows[ny][nx] != color:
				rows[ny][nx] = "K"
	for i in range(3, 13):
		x, y = i, 15 - i - 1
		rows[y][x] = color
	ICONS[name] = ["".join(r) for r in rows]


