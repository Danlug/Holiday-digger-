#!/usr/bin/env python3
"""import_move.py — нарезка авторского листа анимаций движения героя.

Лист: три ряда по восемь кадров, кадры сгруппированы по четыре — шесть
анимаций. Что где, определено по содержимому (см. GROUPS ниже), а не по
порядку: художник прислал шесть групп на четыре нужных анимации, две из них
— вторые варианты (ещё один цикл шага и ранец с одним винтом вместо двух).

Раньше ходьба, падение и оба полёта собирались процедурно из одной стоячей
позы (import_art.anim_walk / anim_fall / anim_fly): полосы тела ездили
покадрово, а винт рисовался прямоугольниками над головой. Нарисованные кадры
лучше во всём, поэтому для героя процедурная сборка движения отключена.
Деду и бабкам она нужна по-прежнему — нарисованных кадров для них нет.

Три вещи, на которых легко ошибиться именно здесь:

  1. Фон вычитается ЗАЛИВКОЙ ОТ КРАЁВ, а не порогом яркости: у персонажа
     чёрная обводка, и порог выел бы её вместе с фоном. Фон тут тёмно-серый
     (41,46,49), обводка почти чёрная — между ними есть зазор, по нему и
     ставится допуск.

  2. Масштаб и линия земли считаются ОДИН раз на весь лист. Выровняешь
     каждый кадр по его собственной рамке — герой запрыгает внутри клетки.

  3. По горизонтали кадры сводятся ПО ГОЛОВЕ (import_art.head_anchor).
     Художник ставил фигуру в каждой клетке по-своему: середина головы
     гуляет по клетке на 17 px исходника, это 4 игровых пикселя — в игре
     такое читается как дрожание. Голова — единственный надёжный якорь:
     она есть в каждом кадре, компактна и вбок почти не ходит; ноги и
     должны двигаться, а рамку кадра растягивают винт, пламя и руки.

Запуск:  python3 tools/import_move.py art/_source/move_sheet.jpg
"""

import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from import_art import (BODY_H, FOOT_PAD, FRAME_H, FRAME_W,  # noqa: E402
                        head_anchor, shrink)
from import_dig import drop_slivers  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# --- сетка листа -----------------------------------------------------------
#
# Все числа получены разбором содержимого, а не делением 1024/8: кадры стоят
# неравномерно, и деление по 128 px разрезало бы фигуры. Порядок был такой:
# заливкой найден фон, по пустым строкам — три полосы рядов (содержимое
# лежит в 29..181, 207..371, 386..542), по пустым столбцам внутри ряда —
# восемь колонок. Границы ниже проведены по серединам пустых промежутков,
# самый узкий промежуток — 15 px, так что запас есть.
ROW_BANDS = [(0, 194), (195, 378), (379, 558)]
COL_CUTS = [0, 127, 256, 376, 507, 641, 762, 884, 1024]
FRAMES = 4                 # кадров в группе; групп две на ряд

BG = (41, 46, 49)          # фон листа
BG_TOL = 14                # обводка героя это (0..14, 0, 0) — до неё далеко

# --- что где на листе ------------------------------------------------------
#
# Группа — (ряд, номер первого кадра). Разбор по содержимому:
#
#   ход      — широкий шаг с наклоном вперёд и махом рук, ноги расходятся
#              на 70 px: единственная явная походка на листе;
#   шаг2     — второй, спокойный вариант шага: корпус прямой, амплитуда
#              вдвое меньше, ступни отрываются от земли по очереди (низ
#              содержимого гуляет на 4 px, как у ходьбы). В игре не идёт —
#              нужен один цикл, и широкий читается лучше;
#   падение  — тело жёсткое, силуэт от кадра к кадру почти не меняется, низ
#              стоит намертво (2 px), руки разведены от корпуса шире, чем в
#              любой другой группе, подол футболки задран на 2 px выше, чем
#              в стоячих кадрах — это встречный поток. Так же «жёстко»
#              нарисованы и обе группы полёта, а ходьба — наоборот;
#   ранец2   — полёт на ранце: два винта на мачте, как на предмете
#              art/items/backpack_propeller (он двухвинтовой);
#   ранец1   — то же, но винт ОДИН. Второй вариант ранца, в игру не идёт:
#              иначе спрайт в полёте не совпадёт с иконкой снаряжения;
#   джет     — полёт на джетпаке: ракета за спиной, пламя и дым из сопла.
#
# Явной группы «стоит спокойно» на листе нет: и в «шаг2», и в «падении»
# ступни отрываются от земли. Поэтому idle не трогаем, он остаётся прежним.
GROUPS = {
    "ход":     (0, 0),
    "шаг2":    (0, 4),
    "падение": (1, 0),
    "ранец2":  (1, 4),
    "ранец1":  (2, 0),
    "джет":    (2, 4),
}

# Что и под каким именем уходит в игру.
OUT = [
    ("walk", "ход"),
    ("fall", "падение"),
    ("fly", "ранец2"),
    ("fly_jet", "джет"),
]

# Спокойная поза, по которой берётся рост: первый кадр падения — герой в нём
# ещё стоит ровно, обе ступни на земле. Это единственная прямая стойка на
# листе, в остальных группах первый кадр тоже стоячий, но с переносом веса.
REF = ("падение", 0)

# Где на листе земля под ногами: в кадрах полёта её нет (в джетпаке ниже
# ступней ещё и пламя с дымом), поэтому линия земли переносится в каждую
# группу ОТ ГОЛОВЫ — по расстоянию «макушка → подошва» из ходьбы. Считается
# один раз на весь лист: иначе герой при взлёте скакнёт по вертикали.


def background_mask(im, bg=None, tol=None):
    """True там, где фон. Заливка от краёв.

    bg/tol задаются, когда лист другой: import_walk.py зовёт эту же заливку
    для листа ходьбы, а фон там темнее (29,25,22). Значения по умолчанию —
    для листа движения, ради которого функция и написана.

    Порогом яркости этот лист резать нельзя: фон (41,46,49) темнее многих
    пикселей джинсов и светлее обводки, и любой порог либо оставит фон, либо
    выест чёрный контур персонажа. Заливка же идёт по связности и до контура
    просто не доходит — он от фона отличается сильно.

    Своя, а не import_art.background_mask: та настроена на светлый лист
    персонажей (217/194) и на тёмно-сером листе не зацепится ни за что.
    """
    px = im.load()
    w, h = im.size
    bg = BG if bg is None else bg
    tol = BG_TOL if tol is None else tol

    def bg_like(p):
        return max(abs(p[i] - bg[i]) for i in range(3)) <= tol

    mask = bytearray(w * h)
    seen = bytearray(w * h)
    stack = []
    for x in range(w):
        stack.append((0, x)); stack.append((h - 1, x))
    for y in range(h):
        stack.append((y, 0)); stack.append((y, w - 1))
    while stack:
        y, x = stack.pop()
        i = y * w + x
        if seen[i]:
            continue
        seen[i] = 1
        if not bg_like(px[x, y]):
            continue
        mask[i] = 1
        if y > 0: stack.append((y - 1, x))
        if y < h - 1: stack.append((y + 1, x))
        if x > 0: stack.append((y, x - 1))
        if x < w - 1: stack.append((y, x + 1))
    return mask


def cut(im, mask, box):
    """Кусок листа с альфой по маске фона. Не обрезается: нужны координаты
    внутри клетки, по ним потом считается якорь."""
    x0, y0, x1, y1 = box
    w = im.size[0]
    out = Image.new("RGBA", (x1 - x0 + 1, y1 - y0 + 1), (0, 0, 0, 0))
    src, dst = im.load(), out.load()
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if not mask[y * w + x]:
                dst[x - x0, y - y0] = src[x, y] + (255,)
    return out


def alpha_count(img):
    """Сколько непрозрачных пикселей. По гистограмме альфы, а не попиксельно:
    вызывается на каждой из 24 клеток."""
    w, h = img.size
    return w * h - img.getchannel("A").histogram()[0]


def main(path):
    sheet = Image.open(path).convert("RGB")
    print("лист:", sheet.size)
    mask = background_mask(sheet)

    # 1. вырезаем все 24 кадра
    cells = {}
    for r, (y0, y1) in enumerate(ROW_BANDS):
        for i in range(len(COL_CUTS) - 1):
            cell = cut(sheet, mask, (COL_CUTS[i], y0, COL_CUTS[i + 1] - 1, y1))
            before = alpha_count(cell)
            # На этом листе кадры стоят с зазорами и через границу клетки
            # ничего не переходит — но лист ещё пришлют в новой версии, и
            # если кадры съедутся, обрывок соседа лучше увидеть в логе, чем
            # потом в игре.
            cell = drop_slivers(cell)
            lost = before - alpha_count(cell)
            if lost:
                print(f"  ! ряд {r + 1} кадр {i + 1}: выброшен обрывок соседнего "
                      f"кадра, {lost} px — проверь границы клеток")
            cells[(r, i)] = cell

    # 2. рост в спокойной позе задаёт масштаб для ВСЕГО листа
    gr, gi = GROUPS[REF[0]]
    ref_box = cells[(gr, gi + REF[1])].getbbox()
    ref_h = ref_box[3] - ref_box[1]
    k = BODY_H / ref_h
    print(f"рост в спокойной позе: {ref_h} px исходника -> {BODY_H} px, "
          f"масштаб {k:.4f}")

    # 3. якорь каждого кадра — голова
    heads = {key: head_anchor(cell, ref_h) for key, cell in cells.items()}

    # 4. расстояние «макушка → подошва» берётся у ходьбы: там ноги стоят на
    #    земле, и её низ — настоящая линия земли. Это же расстояние потом
    #    задаёт землю в группах, где земли не нарисовано.
    wr, wi = GROUPS["ход"]
    walk_keys = [(wr, wi + n) for n in range(FRAMES)]
    walk_ground = max(cells[key].getbbox()[3] for key in walk_keys)
    walk_head = sorted(heads[key][1] for key in walk_keys)[FRAMES // 2]
    stand = walk_ground - walk_head
    print(f"макушка -> подошва в ходьбе: {stand} px исходника")

    written = []
    for name, group in OUT:
        r, first = GROUPS[group]
        keys = [(r, first + n) for n in range(FRAMES)]
        # Одна линия земли на группу: внутри группы кадры сохраняют свои
        # смещения (подскок, поджатые ноги), между группами герой не прыгает.
        ground = sorted(heads[key][1] for key in keys)[FRAMES // 2] + stand

        out = Image.new("RGBA", (FRAME_W * FRAMES, FRAME_H), (0, 0, 0, 0))
        for n, key in enumerate(keys):
            cell = cells[key]
            b = cell.getbbox()
            piece = cell.crop(b)
            tw = max(1, round(piece.size[0] * k))
            th = max(1, round(piece.size[1] * k))
            small = shrink(piece, (tw, th), colors=28)

            # голова — в середину кадра по X, земля группы — на линию подошв
            dx = n * FRAME_W + FRAME_W // 2 - round((heads[key][0] - b[0]) * k)
            dy = FRAME_H - FOOT_PAD - round((ground - b[1]) * k)
            out.alpha_composite(small, (dx, dy))

        dst = os.path.join(ROOT, "art", "character", "boy", name + ".png")
        out.save(dst)
        # герой ищется обоими рендерерами в art/character/
        out.save(os.path.join(ROOT, "art", "character", name + ".png"))
        written.append(name)
        # Разброс середины головы по готовым кадрам — та самая проверка на
        # шатание вбок. Доли пикселя — это округление при укладке кадра,
        # целый пиксель и больше означал бы, что якорь не сработал.
        hs = [head_anchor(out.crop((n * FRAME_W, 0, (n + 1) * FRAME_W, FRAME_H)),
                          BODY_H)[0] for n in range(FRAMES)]
        print(f"  {name:8s} <- «{group}», ряд {r + 1}, кадры "
              f"{first + 1}-{first + FRAMES}, земля y={ground}, "
              f"голова гуляет на {max(hs) - min(hs):.2f} px")

    print("записано наборов:", len(written))


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("укажи путь к листу: python3 tools/import_move.py sheet.jpg")
    main(sys.argv[1])
