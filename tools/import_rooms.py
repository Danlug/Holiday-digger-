#!/usr/bin/env python3
"""import_rooms.py — три авторских фона комнат в игровые задники.

Комнаты — не картинки-заставки, а настоящие игровые пространства: герой в
них ходит, камера едет за ним по горизонтали. Экран 224×480 (поле ~440 px),
поэтому комната обязана быть ШИРЕ экрана — иначе ехать некуда.

Что делает скрипт:

  1. Масштабирует исходник (1024×572) в высоту 448 px — это ровно 14 клеток
     по 32. Ширина считается из пропорций исходника: 1024·448/572 = 802.0 px.
     Мы кладём 800 — 25 клеток ровно. Разница 2 px на 802, то есть 0.25 %:
     это округление до клеточной сетки, а не растягивание, и на глаз его нет.
     Зато другому агенту (и уровню) достаётся целое число клеток, а не 25.06.

  2. Квантует палитру. JPEG размывает пиксель-арт: на плоской стене остаётся
     грязь из соседних оттенков, а при уменьшении она превращается в шум.
     Так же лечили дом (import_house) и тайлы (import_tiles).

  3. Пишет рядом json с опорными точками — В ДОЛЯХ ширины и высоты. Доли, а
     не пиксели: рисунок перережут или перемасштабируют — доли переживут. По
     ним другой агент расставляет кнопки (дверь, кровать, сундук, верстак).

ФОН НЕ ВЫРЕЗАЕТСЯ. У дома и персонажей заливка от краёв снимала небо, здесь
снимать нечего: комната непрозрачна от края до края, это задник.

Опорные точки замерены по ИСХОДНИКУ, в пикселях, по увеличенным кропам с
координатной сеткой (tools/, временные превью). Каждое число ниже подписано
тем, что именно в этом месте нарисовано.

Запуск:  python3 tools/import_rooms.py
"""

import json
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TILE = 32

OUT_CELLS_X = 25          # ширина комнаты в клетках: ~3.5 экрана по 224 px
OUT_CELLS_Y = 14          # высота: 448 px, чуть больше игрового поля в 440
PALETTE_COLORS = 96       # см. комментарий в quantize()


def px(source_size, frac):
    """Доля -> пиксель исходника. Только для печати в отчёт."""
    return round(source_size * frac)


# ---------------------------------------------------------------------------
# Опорные точки. Все числа — доли от ширины (x) и высоты (y) ИСХОДНИКА,
# и ровно те же доли работают для готового png: масштаб равномерный.
#
# floor_y — линия, по которой стоят НОГИ героя. Выбрана не «где начинается
# пол» (пол уходит вглубь в перспективе, единой линии у него нет), а там, где
# герой читается стоящим ПЕРЕД мебелью: ниже ножек стола, ножек кровати,
# нижнего края сундука. Выше — герой утонет в мебели, ниже — упрётся в край.
# ---------------------------------------------------------------------------

ROOMS = {
    "room_hall": {
        # Салон: вход справа через панорамное остекление, в глубине две двери.
        "anchors": {
            # Пол: доски у порога. Плинтус левой стены садится на пол на
            # y≈500, ножки стульев кончаются на y≈450 — 518 ниже всего этого.
            "floor_y": (None, 518 / 572),
            # Левая дверь в глубине: полотно по горизонтали 349..391 (найдено
            # по тёплому тону полотна), тёмная коробка 332..411. Центр 371.
            # По вертикали: верх коробки 200, стык стены с полом 355.
            "door_left": (371 / 1024, 277 / 572),
            # Правая дверь: полотно 444..505, коробка 436..516. Центр 476.
            "door_right": (476 / 1024, 277 / 572),
            # Веранда: остекление начинается от откоса на x≈745 и идёт до
            # правого края 1024, центр проёма 885. По вертикали — по линии
            # пола: именно туда герой подходит, чтобы выйти на улицу.
            # (Порог-нащельник идёт наискось: (737,440)-(907,512).)
            "veranda": (885 / 1024, 518 / 572),
        },
    },
    "room_bedroom": {
        # Спальня ночью.
        "anchors": {
            # Пол: основание кровати садится на пол на y≈505, тумбочка слева
            # стоит ножками на y≈554. 532 — между ними, перед кроватью.
            "floor_y": (None, 532 / 572),
            # Кровать целиком (со спинкой): x 49..626, y 200..509.
            # Центр этого прямоугольника — (337, 354).
            "bed": (337 / 1024, 354 / 572),
        },
        # Прямоугольник кровати — чтобы кнопку можно было растянуть по нему,
        # а не ставить точкой.
        "boxes": {"bed": (49 / 1024, 200 / 572, 626 / 1024, 509 / 572)},
    },
    "room_workshop": {
        # Мастерская в подвале: лестница слева, верстак по центру, сундук,
        # справа на стене швабры и удочки.
        "anchors": {
            # Пол: каменные плиты. Низ сундука y≈512, низ швабр y≈512,
            # ножки верстака кончаются на y≈490. 535 ниже всего.
            "floor_y": (None, 535 / 572),
            # Лестница: нижняя ступень лежит полосой x 0..179, её проступь на
            # y≈470; тетива упирается в пол на (196, 498). Точка схода со
            # ступеней на плиты — (105, 482).
            "stairs_bottom": (105 / 1024, 482 / 572),
            # Верстак: столешница x 333..768, её плоскость y 312..333.
            # Центр столешницы — (550, 322).
            "workbench": (550 / 1024, 322 / 572),
            # Сундук: короб x 305..473, y 442..512; откинутая крышка уводит
            # верх до y=338. Центр открытого сундука (там же лежит добро) —
            # (389, 445).
            "chest": (389 / 1024, 445 / 572),
            # Стена со швабрами и удочками — оттуда снимается ржавая кирка.
            # Кисти швабр висят на y 217..297 при x 822..917, удочки идут
            # наискось по x 910..965. Середина этой связки — (860, 330).
            "tools_wall": (860 / 1024, 330 / 572),
        },
        "boxes": {"chest": (305 / 1024, 338 / 572, 473 / 1024, 512 / 572),
                  "workbench": (333 / 1024, 300 / 572, 768 / 1024, 490 / 572)},
    },
}


def quantize(img):
    """Палитра в 96 цветов.

    48, как у дома, здесь мало: у дома плоский фасад, а в комнате есть и
    ночной градиент от лампы (спальня), и небо с зеленью за стеклом (салон).
    На 48 цветах градиент лампы рвётся кольцами. 96 их держит и всё ещё
    заметно чище исходного JPEG-шума — проверено на превью 1:1.
    """
    return img.quantize(colors=PALETTE_COLORS,
                        method=Image.MEDIANCUT).convert("RGB")


def main():
    out_w, out_h = OUT_CELLS_X * TILE, OUT_CELLS_Y * TILE
    os.makedirs(os.path.join(ROOT, "art", "env"), exist_ok=True)

    for name, spec in ROOMS.items():
        src = os.path.join(ROOT, "art", "_source", name + ".jpg")
        im = Image.open(src).convert("RGB")
        sw, sh = im.size

        exact_w = sw * out_h / sh
        small = quantize(im.resize((out_w, out_h), Image.LANCZOS))
        out = os.path.join(ROOT, "art", "env", name + ".png")
        small.save(out)

        anchors = {}
        for key, (fx, fy) in spec["anchors"].items():
            rec = {}
            if fx is not None:
                rec["x"] = round(fx, 4)
                rec["px_x"] = round(fx * out_w)
                rec["cell_x"] = round(fx * out_w / TILE, 2)
            if fy is not None:
                rec["y"] = round(fy, 4)
                rec["px_y"] = round(fy * out_h)
                rec["cell_y"] = round(fy * out_h / TILE, 2)
            anchors[key] = rec

        meta = {
            "source": "art/_source/%s.jpg" % name,
            "source_size": [sw, sh],
            "width": out_w,
            "height": out_h,
            "cells_x": OUT_CELLS_X,
            "cells_y": OUT_CELLS_Y,
            "tile": TILE,
            "screen": [224, 440],
            "screens_wide": round(out_w / 224.0, 2),
            "anchors": anchors,
            "_note": ("Доли x/y — от ширины и высоты картинки (0..1), замерены "
                      "по исходнику. px_* и cell_* — те же точки, пересчитанные "
                      "для этого png; при перересборке пересчитаются сами."),
            "_aspect_note": ("точная ширина при высоте %d была бы %.1f px; "
                             "округлена до %d (%d клеток), расхождение %.2f%%"
                             % (out_h, exact_w, out_w, OUT_CELLS_X,
                                abs(out_w - exact_w) / exact_w * 100.0)),
        }
        if "boxes" in spec:
            meta["boxes"] = {k: {"x0": round(b[0], 4), "y0": round(b[1], 4),
                                 "x1": round(b[2], 4), "y1": round(b[3], 4)}
                             for k, b in spec["boxes"].items()}

        with open(os.path.join(ROOT, "art", "env", name + ".json"), "w",
                  encoding="utf-8") as f:
            f.write(json.dumps(meta, ensure_ascii=False, indent="\t") + "\n")

        print("%-14s %d×%d (%d×%d клеток, %.2f экрана по ширине)"
              % (name, out_w, out_h, OUT_CELLS_X, OUT_CELLS_Y, out_w / 224.0))
        for key, rec in anchors.items():
            print("    %-14s %s" % (key, rec))


if __name__ == "__main__":
    main()
