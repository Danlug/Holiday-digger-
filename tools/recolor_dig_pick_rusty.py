#!/usr/bin/env python3
"""recolor_dig_pick_rusty.py — ржавая анимация копки кирки из стальной.

Задача владельца (дословно): «когда он копает ржавой киркой анимация
ужасная, скопируй анимацию как у железной кирки, только сделай её ржавой».

ЧТО БЫЛО НЕ ТАК. art/character/boy/dig_pick_rusty.png (и его плоская копия
art/character/dig_pick_rusty.png, по которой лист реально ищет рендерер —
см. ниже про OUT_FLAT) — 8 кадров 192×144,
см. scripts/player/character_view.gd SHEET_FRAME["dig_pick_rusty"]) — вовсе
не анимация копки тайла. Это отдельная одноразовая сценка «разбить лежащий
камень-валун»: герой стоит (кадр 0), заносит кирку (1-2) и бьёт по
НЕПОДВИЖНОМУ камню на земле, который трескается и разлетается на обломки
(3-7) — камня в обычной копке нет, и последовательность не зациклена как
взмах. Похоже, актив на самом деле принадлежит сюжетной сцене «рюкзак»
(там владелец отдельно видел этот же разлетающийся камень) и был по ошибке
переиспользован как ряд копки. dig_pick.png (стальная кирка) — наоборот,
нормальный зацикленный взмах: занос (0-2), удар с смазом и пылью у тайла
(3), возврат (4-7).

ФИКС. Не рисуем новую анимацию (генерации изображений нет) — берём
СОД�ержимое кадров dig_pick.png как есть (тот самый хороший взмах) и красим
только металл бойка в ржавый тон, целиком оставляя позы, смаз и пыль. Результат
кладём поверх dig_pick_rusty.png — тем самым ржавая кирка копает так же, как
стальная, только цветом ржавая, как и просил владелец.

ЦВЕТ. В отличие от tools/rig_drill_recolor.py (там голова кирки — чистый
цветной металл, а рукоять — отдельный нейтральный "деревянный" оттенок,
который можно исключить по Hue), у art/items/pickaxe_rusty.png ГОЛОВКА И
РУКОЯТЬ нарисованы ОДНИМ ржавым цветом (инструмент весь трухлявый) — если
взять оттуда фильтр "выкинуть дерево 0..70°/345..360°", он выкинет и саму
ржавчину (она тоже в этом диапазоне) и оставит для взвешивания только шум
на краях спрайта. Поэтому здесь свой _rusty_reference_hsv: то же взвешенное
по насыщенности круговое среднее Hue (см. докстринг rig_drill_recolor.
_pickaxe_metal_hsv), но БЕЗ исключения по Hue — на pickaxe_rusty.png нет
отдельной нейтральной рукояти, которую нужно было бы отсеивать.

МАСКА «ЭТО БОЁК». У dig_pick.png простой ахроматичный порог (см.
rig_drill_recolor._achromatic) сам по себе ловит не только стальной боёк, но
и серые штаны/ботинки героя — оба региона проверены напрямую по пикселям и
дают похожий (8..15) размах max-min RGB, различить их только по цвету
нельзя. Боёк при этом на каждом кадре — единственный представитель этого
цвета В СВОЁМ прямоугольнике кадра: кирка описывает дугу взмаха (кадры 0-2 —
занесена над головой слева, 3 — смаз+удар справа у тайла, 4-7 — опускается и
возвращается у бедра), и её положение НЕ пересекается по прямоугольнику с
ногами героя, которые почти не двигаются между кадрами (силуэт ног/обуви на
всех восьми кадрах лежит в x≈40..115, y≈63..137 — см. отчёт агента,
прямоугольники по scipy.ndimage.label). Поэтому маска — тот же приём, что и
у rig_drill_recolor._side_drill_mask: ахроматичность И «в прямоугольнике,
где в этом конкретном кадре сейчас боёк» (см. FRAME_ZONES ниже, подобраны
по кадрам — см. отчёт агента с покомпонентной раскраской, там же зоны
проверены на отсутствие пересечения с ногами, лицом и волосами на всех
восьми кадрах). На кадре 3 в эту же зону попадает и смазанная дуга взмаха
(она рисуется тем же серым металлом и физически смыкается с бойком в точке
удара) — она красится вместе с бойком: на самых ярких пикселях дуги общая
кривая насыщенности (см. rig_drill_recolor._recolor_pixels) и так сводит
насыщенность почти к нулю, так что дуга остаётся бледной, просто с тёплым
оттенком, как и должно быть у смаза.

Маска — приближение, не идеальная посегментная вырезка (тот же допуск, что
и в rig_drill_recolor: единичные пиксели пыли/камня у бойка на кадре 3-4
попадают в маску и красятся заодно — это мелкий рассеянный шум у самого
бойка, а не пятно на одежде/коже, и на телефонном экране не отличим от
самого бойка). Каждый из восьми кадров проверен агентом по отдельности
(рендер с подсвеченными компонентами) на то, что маска не задевает штаны,
рубашку, кожу или волосы ни на одном кадре.

Запуск:  python3 tools/recolor_dig_pick_rusty.py
"""

import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHAR_DIR = os.path.join(ROOT, "art", "character", "boy")
CHAR_FLAT_DIR = os.path.join(ROOT, "art", "character")
ITEMS_DIR = os.path.join(ROOT, "art", "items")

SRC = os.path.join(CHAR_DIR, "dig_pick.png")
OUT = os.path.join(CHAR_DIR, "dig_pick_rusty.png")
# см. tools/import_dig.py, конец main(): "герой ищется рендерерами в
# art/character/" — CharacterView._ready грузит лист по фиксированному пути
# "res://art/character/" + имя + ".png" БЕЗ поддиректории "boy", так что
# правленный лист нужно положить туда же, не только в art/character/boy/
# (там же лежит исходный dig_pick.png, которым правится этот файл, и его
# читают другие импортёры, поэтому boy/-копия тоже остаётся).
OUT_FLAT = os.path.join(CHAR_FLAT_DIR, "dig_pick_rusty.png")
REF = os.path.join(ITEMS_DIR, "pickaxe_rusty.png")

FRAME_W, FRAME_H, FRAMES = 192, 144, 8

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from rig_drill_recolor import _rgb_to_hsv_np, _hsv_to_rgb_np, _achromatic  # noqa: E402

# ---------------------------------------------------------------------------
# Зона «здесь сейчас боёк» по каждому из 8 кадров взмаха dig_pick.png —
# подобрана по РАСПОЛОЖЕНИЮ (см. докстринг файла), проверена рендером с
# раскрашенными связными компонентами (отчёт агента): в каждом прямоугольнике
# лежит ровно боёк (плюс на кадре 3 — смазанная дуга удара, физически с ним
# слитая), ни разу нога/ботинок/лицо/волосы героя, чей силуэт в этих кадрах
# держится в x≈40..115, y≈63..137 и ни в одну из зон не заходит.
# (x0, x1, y0, y1) — полуоткрытые по x1/y1, как срез numpy.
# ---------------------------------------------------------------------------
FRAME_ZONES = [
    (38, 72, 4, 58),      # 0: занесена над головой слева
    (38, 68, 0, 53),      # 1: занесена выше
    (52, 90, 0, 47),      # 2: начало взмаха вниз-вправо
    (102, 172, 6, 131),   # 3: удар — боёк + смазанная дуга у тайла
    (104, 152, 88, 140),  # 4: у самой земли, отдача
    (44, 82, 10, 55),     # 5: подъём от бедра
    (43, 89, 37, 88),     # 6: возврат, кирка на уровне груди
    (34, 75, 57, 113),    # 7: почти в исходном положении
]

# Опорная светлота бойка ДО перекраски (среднее V маски бойка на кадре 0,
# см. отчёт агента) — знаменатель масштаба V в _recolor_pixels, тот же
# приём, что и DRILL_BASE_V в rig_drill_recolor.
PICK_BASE_V = 0.523


def _rect_zone(shape, x0, x1, y0, y1):
    m = np.zeros(shape, dtype=bool)
    m[y0:y1, x0:x1] = True
    return m


def _rusty_reference_hsv(path):
    """Оттенок/насыщенность/светлота ржавого металла с pickaxe_rusty.png.

    Тот же взвешенный по насыщенности круговой приём, что и
    rig_drill_recolor._pickaxe_metal_hsv, но БЕЗ исключения "деревянных"
    оттенков 0..70°/345..360°: на этой иконке головка и рукоять — один и тот
    же ржавый цвет (см. докстринг файла), исключение по Hue выбросило бы
    саму ржавчину, а не дерево.
    """
    im = Image.open(path).convert("RGBA")
    arr = np.array(im)
    a = arr[..., 3]
    h, s, v = _rgb_to_hsv_np(arr[..., :3])
    keep = a > 10
    h_k, s_k, v_k = h[keep], s[keep], v[keep]
    sin_sum = float(np.sum(s_k * np.sin(h_k * 2 * np.pi)))
    cos_sum = float(np.sum(s_k * np.cos(h_k * 2 * np.pi)))
    mean_h = (np.arctan2(sin_sum, cos_sum) / (2 * np.pi)) % 1.0
    s_sum = float(np.sum(s_k))
    mean_s = float(np.sum(s_k * s_k) / s_sum) if s_sum > 1e-9 else 0.0
    mean_v = float(np.mean(v_k)) if v_k.size else 0.5
    return mean_h * 360.0, mean_s, mean_v


def _pick_mask(frame, zone_rect):
    ach = _achromatic(frame)
    zone = _rect_zone(ach.shape, *zone_rect)
    return ach & zone


def _recolor_pixels(arr, mask, target_h_deg, target_s, target_v):
    """Красит пиксели под маской в ржавый металл.

    Тот же приём, что и rig_drill_recolor._recolor_pixels (держит V как
    масштаб, не как замену — тени и блики бойка остаются на месте, просто
    вся шкала светлот сдвигается к ржавчине; насыщенность модулирована по
    собственной яркости пикселя). Переписан локально, а не импортирован,
    потому что там масштаб V завязан на DRILL_BASE_V бура, а у бойка кирки
    своя опорная светлота — PICK_BASE_V (см. её докстринг)."""
    out = arr.copy()
    if not np.any(mask):
        return out
    region = arr[mask][..., :3]
    _, _, v = _rgb_to_hsv_np(region.reshape(1, -1, 3))
    v = v.reshape(-1)
    target_h = (target_h_deg / 360.0) % 1.0
    sat_curve = np.clip(1.25 - v, 0.45, 1.35)
    new_s = np.clip(target_s * sat_curve, 0.0, 1.0)
    new_h = np.full_like(v, target_h)
    v_scale = np.clip(target_v / PICK_BASE_V, 0.5, 1.4)
    new_v = np.clip(v * v_scale, 0.03, 1.0)
    new_rgb = _hsv_to_rgb_np(new_h, new_s, new_v)
    out_rgb = out[..., :3]
    out_rgb[mask] = new_rgb
    return out


def main():
    target_h, target_s, target_v = _rusty_reference_hsv(REF)
    print("ржавый металл (с pickaxe_rusty.png): H=%.1f S=%.3f V=%.3f"
          % (target_h, target_s, target_v))

    im = Image.open(SRC).convert("RGBA")
    sheet = np.array(im)
    out = sheet.copy()
    for i in range(FRAMES):
        x0 = i * FRAME_W
        frame = sheet[:, x0:x0 + FRAME_W]
        mask = _pick_mask(frame, FRAME_ZONES[i])
        out[:, x0:x0 + FRAME_W] = _recolor_pixels(
            frame, mask, target_h, target_s, target_v)
        print("  кадр %d: перекрашено %d px" % (i, int(mask.sum())))

    Image.fromarray(out).save(OUT)
    print("-> %s" % OUT)
    Image.fromarray(out).save(OUT_FLAT)
    print("-> %s (копия для рендерера, см. комментарий у OUT_FLAT)" % OUT_FLAT)


if __name__ == "__main__":
    sys.exit(main())
